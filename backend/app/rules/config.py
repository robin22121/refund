def by_year(table: dict[int, int], year: int) -> int:
    """연도별 표에서 그해 값(없으면 가장 가까운 이전 해 값)을 찾는다."""
    past = [y for y in table if y <= year]
    return table[max(past)] if past else table[min(table)]
